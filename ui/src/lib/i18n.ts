const DICTS: Record<Locale, Record<Key, string>> = { en, "pt-BR": ptBR };

const isLocale = (v: unknown): v is Locale => v === "en" || v === "pt-BR";
const saved = load<string>("locale", "en");
const [locale, setLocaleSignal] = createSignal<Locale>(isLocale(saved) ? saved : "en");
if (typeof document !== "undefined") document.documentElement.lang = locale();

export { locale };

export function setLocale(l: Locale) {
  setLocaleSignal(l);
  save("locale", l);
  if (typeof document !== "undefined") document.documentElement.lang = l;
}

/** Accepts `en`, `pt`, `pt-br`, `pt-BR`… */
export function parseLocale(s: string): Locale | null {
  const v = s.trim().toLowerCase();
  if (v === "en" || v.startsWith("en-") || v === "english") return "en";
  if (v === "pt" || v === "pt-br" || v === "pt_br" || v.startsWith("portugu")) return "pt-BR";
  return null;
}

/** Text for `key` in the current language, `{name}` placeholders filled from `vars`. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  const text = DICTS[locale()][key] ?? en[key];
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : text;
}

/** Translated text for a core error kind, if there is one. */
export function errorText(kind: string, detail: string | undefined): string | null {
  const key = `error.${kind}` as Key;
  return key in en ? t(key, { detail: detail ?? "" }) : null;
}
